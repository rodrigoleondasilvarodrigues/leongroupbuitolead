// Decodifica uma vez, no start do isolate, e reusa o mesmo buffer em toda
// requisição. Decodificar por requisição gastaria CPU do Worker de graça.
const bytes = (b64) => {
  const bin = atob(b64);
  const u = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) u[i] = bin.charCodeAt(i);
  return u;
};
const FAVICON = bytes(FAVICON_64_B64);
const ICONE = bytes(ICONE_256_B64);

// Um ano de cache: o ícone da marca não muda. Se mudar, o nome do arquivo muda.
const CABECALHOS = {
  "Content-Type": "image/png",
  "Cache-Control": "public, max-age=31536000, immutable",
};

/* Rotas do ícone. Ficam ANTES do portão de sessão de propósito: a aba de
   login também precisa mostrar o leão, e o formulário do cliente é público. */
export function rotaIcone(caminho) {
  if (caminho === "/favicon.ico" || caminho === "/favicon.png")
    return new Response(FAVICON, { headers: CABECALHOS });
  if (caminho === "/apple-touch-icon.png" || caminho === "/apple-touch-icon-precomposed.png")
    return new Response(ICONE, { headers: CABECALHOS });
  return null;
}

